//OPERATOR ASSIGNMENT

/*
Digunakan untuk menetapkan nilai ke variabel

    = (assignment dasar)
    += (penjumlahan dan assignment)
    -= (pengurangan dan assignment)
    *= (perkalian dan assignment)
    /= (pembagian dan assignment)
    %= (modulus dan assignment)
*/

//ASSIGNENT DASAR =
let nama = 'fauzi'
console.log (nama)      //output fauzi

//PENJUMLAHAN DAN ASSIGNMENT
let r = 2
r += 3
console.log (r)         //output 5

//PENGURANGAN DAN ASSIGMENT
let p = 7
p -= 3
console.log (p)         //output 4

//PERKALIAN DAN ASSIGNMENT
let q = 5
q *= 4
console.log (q)         //output 20

//PEMBAGIAN DAN ASSIGNMENT
let t = 30
t /= 6
console.log (t)         //output 5

//MODULUS DAN ASSIGNMENT
let s = 13
s %= 4
console.log(s)          //output 1