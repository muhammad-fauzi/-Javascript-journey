//OPERATOR

/* Operator adalah simbol yang digunakan untuk melakukan operasi matematika,
seperti tambah, kurang, bagi, kali.

Jenis-jenis Operator:
    1. operator aritmatika
    2. operator assignment
    3. operator perbandingan
    4. operator logika
    5. operator ternary
*/

//PEMBAHASAN
/* 1. Operator Aritmatika

    + (penjumlahan)
    - (pengurangan)
    / (pembagian)
    * (perkalian)
    % (modulus / sisa bagi)
    ** (eksponen / pangkat)
    ++ (increment / menambah satu nilai)
    -- (decrement / mengurangi satu nilai)
*/

//PENJUMLAHAN
let a = 10
let b = 5
let jumlah = a + b
console.log (jumlah)     //output 15

//PENGURANGAN
let d = 10
let e = 5
let pengurangan = d - e
console.log (pengurangan)     //output 5

//PERKALIAN
let g = 6
let h = 2
let perkalian = g * h
console.log (perkalian)     //output 12

//PEMBAGIAN
let j = 12
let k = 2
let pembagian = j / k
console.log (pembagian)     //output 6

//MODULUS ATAU SISA BAGI
let l = 20
let m = 6
let modulus = l % m
console.log (modulus)       //output 2

//EKSPONEN ATAU AKAR PANGKAT
let n = 4
let o = 2
let pangkat = n ** o
console.log (pangkat)       //output 16

//INCREAMENT ATAU PENAMBAHAN SATU NILAI
let p = 2
p++
console.log (p)             //output 3

//DECREAMENT ATAU PENGURANGAN SATU NILAI

let q = 5
q--
console.log (q)             //output 4
